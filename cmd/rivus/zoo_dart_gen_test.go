package main

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
	"sync"
	"testing"
)

// What the Dart zoo derives from its directories, so that a pull request that adds a cell (or a skeleton package) touches
// only the files of that cell, and no list that every other pull request touches too:
//
//   - bench/zoo-dart/exec/lib/cases.dart (the imports and the registerAll() of the cells) is generated from the files of
//     bench/zoo-dart/cells/lib that have a `void register()`. It is not committed (.gitignore): the tests write it
//     (zooDartRoot), and `make zoo-dart-gen` writes it for `dart analyze` and for a person who runs dart by hand.
//   - bench/zoo-dart/cells/pubspec.yaml is committed (rivus and several scripts read the cells as a package), and it is the
//     one of the head below, with a path dependency for every directory of cells/packages in the order of the names.
//     TestZooDartGenerate fails when it is not that; `make zoo-dart-gen` (the -update flag) rewrites it.

const zooDartPubspecHead = `name: zoo_cells
description: "The cells of the Dart zoo (docs/DESIGN-zoo.md). rivus analyses this directory."
publish_to: none
environment:
  sdk: ^3.10.0
dependencies:
`

var zooDartGenOnce sync.Once

// zooDartCasesSource is the text of exec/lib/cases.dart for the cells under root/cells/lib: one import per cell (the order
// of the paths), and one call of register() per cell in the same order.
func zooDartCasesSource(root string) (string, error) {
	lib := filepath.Join(root, "cells", "lib")
	var rels []string
	err := filepath.WalkDir(lib, func(p string, d os.DirEntry, err error) error {
		if err != nil || d.IsDir() || !strings.HasSuffix(p, ".dart") {
			return err
		}
		b, err := os.ReadFile(p)
		if err != nil {
			return err
		}
		if regexp.MustCompile(`(?m)^void register\(\)`).Match(b) {
			rel, _ := filepath.Rel(lib, p)
			rels = append(rels, filepath.ToSlash(rel))
		}
		return nil
	})
	if err != nil {
		return "", err
	}
	sort.Strings(rels)
	var b strings.Builder
	b.WriteString("// GENERATED by cmd/rivus TestZooDartGenerate (`make zoo-dart-gen`) from the files of cells/lib that have a\n")
	b.WriteString("// `void register()`; not committed (.gitignore). The harness calls every cell's register().\n")
	alias := map[string]string{}
	for _, r := range rels {
		a := regexp.MustCompile(`[^a-zA-Z0-9]+`).ReplaceAllString(strings.TrimSuffix(r, ".dart"), "_")
		if other, ok := alias[a]; ok {
			return "", fmt.Errorf("the cells %s and %s make the same alias %s", other, r, a)
		}
		alias[a] = r
		fmt.Fprintf(&b, "import 'package:zoo_cells/%s' as %s;\n", r, a)
	}
	b.WriteString("\nvoid registerAll() {\n")
	for _, r := range rels {
		a := regexp.MustCompile(`[^a-zA-Z0-9]+`).ReplaceAllString(strings.TrimSuffix(r, ".dart"), "_")
		fmt.Fprintf(&b, "  %s.register();\n", a)
	}
	b.WriteString("}\n")
	return b.String(), nil
}

// zooDartPubspecSource is the text of cells/pubspec.yaml.
func zooDartPubspecSource(root string) (string, error) {
	ents, err := os.ReadDir(filepath.Join(root, "cells", "packages"))
	if err != nil {
		return "", err
	}
	var names []string
	for _, e := range ents {
		if e.IsDir() {
			names = append(names, e.Name())
		}
	}
	sort.Strings(names)
	var b strings.Builder
	b.WriteString(zooDartPubspecHead)
	for _, n := range names {
		fmt.Fprintf(&b, "  %s:\n    path: packages/%s\n", n, n)
	}
	return b.String(), nil
}

// writeIfChanged writes the file only when its content differs: `dart run` resolves again when a pubspec is newer than
// the package config.
func writeIfChanged(path, content string) (bool, error) {
	if old, err := os.ReadFile(path); err == nil && string(old) == content {
		return false, nil
	}
	// a checkout has no directory for a file that is not committed (exec/lib holds only cases.dart)
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return false, err
	}
	return true, os.WriteFile(path, []byte(content), 0o644)
}

// zooDartGenerateCases writes exec/lib/cases.dart once per test binary.
func zooDartGenerateCases(t testing.TB, root string) {
	t.Helper()
	zooDartGenOnce.Do(func() {
		src, err := zooDartCasesSource(root)
		if err == nil {
			_, err = writeIfChanged(filepath.Join(root, "exec", "lib", "cases.dart"), src)
		}
		if err != nil {
			t.Fatalf("cases.dart: %v", err)
		}
	})
}

// TestZooDartGenerate writes exec/lib/cases.dart, and holds cells/pubspec.yaml to the directories of cells/packages
// (-update rewrites it: `make zoo-dart-gen`).
func TestZooDartGenerate(t *testing.T) {
	root := zooDartRoot(t)
	zooDartGenerateCases(t, root)
	want, err := zooDartPubspecSource(root)
	if err != nil {
		t.Fatal(err)
	}
	path := filepath.Join(root, "cells", "pubspec.yaml")
	if *updateDogfoodFlows {
		if _, err := writeIfChanged(path, want); err != nil {
			t.Fatal(err)
		}
		return
	}
	got, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	if string(got) != want {
		t.Errorf("bench/zoo-dart/cells/pubspec.yaml is not the one of the directories of cells/packages (a path dependency for each, in the order of the names): run `make zoo-dart-gen`\nwant:\n%s", want)
	}
}
