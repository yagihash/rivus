// TestSandboxedBuildScriptCannotEscape: a build script that is hostile on purpose (extractor/rust/test/hostile_sandbox) runs the probe
// (internal/sandbox/probe), which tries to get out in every way that the tests of the sandbox know of; it is built by the extractor under
// the sandbox, the way a project is. What the probe says goes into the IR (the report of the build script): every check must say BLOCKED.
// It touches the environment of the user in the harmless way of the design (a unique name, removed after), so it needs RIVUS_SBX_RED=1.
func TestSandboxedBuildScriptCannotEscape(t *testing.T) {
	t.Parallel()
	if os.Getenv("RIVUS_SBX_RED") != "1" {
		t.Skip("set RIVUS_SBX_RED=1 (it runs the probe, which makes harmless marks outside the sandbox if it gets out)")
	}
	rust := os.Getenv("RIVUS_RUST")
	if rust == "" {
		skipOrFail(t, "RIVUS_RUST")
	}
	probe := filepath.Join(t.TempDir(), "probe")
	if out, err := exec.Command("go", "build", "-o", probe, "../../internal/sandbox/probe").CombinedOutput(); err != nil {
		t.Fatalf("building the probe: %v\n%s", err, out)
	}
	outside := t.TempDir() // a directory of the test that the build may not write to
	canary := filepath.Join(outside, "canary.txt")
	os.WriteFile(canary, []byte("a fake secret\n"), 0o644)
	project, _ := filepath.Abs("../../extractor/rust/test/hostile_sandbox")
	extractor, _ := filepath.Abs(rust)
	realHome, _ := os.UserHomeDir()
	args := []string{"-home", realHome, "-id", "e2e" + filepath.Base(outside), "-dir", outside, "-canary", canary, "-sensitive",
		"-only", "read_canary,write_outside,write_home,defaults_write,launchagents_file,shell_rc_file,osascript_finder_folder,launchctl_submit,open_finder,pbpaste,securityd_reachable,dns_socket,shm_open,crontab_list,unix_socket_docker"}
	iso := &isolationOpts{
		extractor: []string{extractor}, timeout: 10 * time.Minute, noFetch: false, stderr: &bytes.Buffer{},
		env:       []string{"RIVUS_PROBE_BIN=" + probe, "RIVUS_PROBE_ARGS=" + strings.Join(args, "\x01")},
		execExtra: []string{probe},
	}
	// the probe is read by path: it is in a temporary directory outside the project
	iso.read = []string{filepath.Dir(probe)}
	out, err := iso.extractRustSandboxed(context.Background(), project, []string{project})
	if err != nil {
		t.Fatalf("the extraction under the sandbox: %v\n%s", err, iso.stderr.(*bytes.Buffer).String())
	}
	report := ""
	for _, l := range strings.Split(string(out), "\n") {
		if i := strings.Index(l, "BLOCKED read_canary"); i >= 0 {
			report = l
			break
		}
	}
	if report == "" {
		t.Fatalf("the report of the build script is not in the IR (the probe did not run?): %d bytes\n%s", len(out), iso.stderr.(*bytes.Buffer).String())
	}
	if strings.Contains(report, "ESCAPED") {
		t.Errorf("the build script got out:\n%s", strings.ReplaceAll(report, ";", "\n"))
	}
	if strings.Contains(report, "PROBE_NOT_RUN") {
		t.Errorf("the probe did not run: %s", report)
	}
}

// TestSandboxFetchReadsNoConfigOfTheProject: the stage that fetches has a network, so the code of the project must not run in it, and what
// the cargo configuration of the project says must not be read (it can name a program, a registry, a proxy). The project here has a
// configuration that makes every request fail if cargo reads it (a proxy that nothing listens on), and so has the CARGO_HOME that an
// earlier run could have left; the dependency is fetched all the same (it needs crates.io: RIVUS_SBX_NET=1).
func TestSandboxFetchReadsNoConfigOfTheProject(t *testing.T) {
	t.Parallel()
	if os.Getenv("RIVUS_SBX_NET") != "1" {
		t.Skip("set RIVUS_SBX_NET=1 (it downloads one small crate from crates.io under the sandbox)")
	}
	rust := os.Getenv("RIVUS_RUST")
	if rust == "" {
		skipOrFail(t, "RIVUS_RUST")
	}
	dir := t.TempDir()
	write := func(name, text string) {
		p := filepath.Join(dir, name)
		os.MkdirAll(filepath.Dir(p), 0o755)
		if err := os.WriteFile(p, []byte(text), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	write("Cargo.toml", "[package]\nname = \"p\"\nversion = \"0.0.0\"\nedition = \"2021\"\n[dependencies]\nitoa = \"=1.0.19\"\n[workspace]\n")
	write("src/lib.rs", "pub fn f(n: u32) -> String { itoa::Buffer::new().format(n).to_string() }\n")
	write("Cargo.lock", "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = \"itoa\"\nversion = \"1.0.19\"\nsource = \"registry+https://github.com/rust-lang/crates.io-index\"\nchecksum = \"3bd1574e617a9a6c1f8f8181bd7e841e1f20e4277607ef28945765188d6284d4\"\n\n[[package]]\nname = \"p\"\nversion = \"0.0.0\"\ndependencies = [\n \"itoa\",\n]\n")
	// a configuration of the project that breaks every request if it is read
	write(".cargo/config.toml", "[http]\nproxy = \"http://127.0.0.1:9\"\n")
	volume, err := cargoVolume(dir)
	if err != nil {
		t.Fatal(err)
	}
	data, _ := rustDataDir()
	cargoHome := filepath.Join(data, volume)
	os.MkdirAll(cargoHome, 0o755)
	defer os.RemoveAll(cargoHome)
	// a configuration that an earlier run left in the CARGO_HOME: it is removed before the stage
	os.WriteFile(filepath.Join(cargoHome, "config.toml"), []byte("[http]\nproxy = \"http://127.0.0.1:9\"\n"), 0o644)
	extractor, _ := filepath.Abs(rust)
	errbuf := &bytes.Buffer{}
	iso := &isolationOpts{extractor: []string{extractor}, timeout: 10 * time.Minute, stderr: errbuf}
	if _, err := iso.extractRustSandboxed(context.Background(), dir, []string{"--no-deps", dir}); err != nil {
		t.Fatalf("the fetch and the extraction: %v\n%s", err, errbuf.String())
	}
	if _, err := os.Stat(filepath.Join(cargoHome, "config.toml")); err == nil {
		t.Errorf("the configuration that was in the CARGO_HOME was not removed")
	}
	if ents, _ := os.ReadDir(filepath.Join(cargoHome, "registry", "src")); len(ents) == 0 {
		t.Errorf("nothing was fetched into the CARGO_HOME of rivus")
	}
}

// TestSandboxAncestorCargoConfig: cargo looks for .cargo/config.toml in every directory above where it is run, so a configuration
// outside the project could change the build (a rustc-wrapper is a program that cargo runs instead of rustc). Under the sandbox the
// directories above the project are not readable, and cargo stops ("Operation not permitted") when it finds a configuration it may not read: rivus looks first, and stops with the name, before anything runs. The wrapper must not run.
func TestSandboxAncestorCargoConfig(t *testing.T) {
	t.Parallel()
	rust := os.Getenv("RIVUS_RUST")
	if rust == "" {
		skipOrFail(t, "RIVUS_RUST")
	}
	if os.Getenv("RIVUS_SBX_RED") != "1" {
		t.Skip("set RIVUS_SBX_RED=1")
	}
	outer := t.TempDir()
	proj := filepath.Join(outer, "proj")
	os.MkdirAll(filepath.Join(proj, "src"), 0o755)
	marker := filepath.Join(outer, "wrapper-ran")
	wrapper := filepath.Join(outer, "wrapper.sh")
	os.WriteFile(wrapper, []byte("#!/bin/sh\ntouch "+marker+"\nexec \"$@\"\n"), 0o755)
	os.MkdirAll(filepath.Join(outer, ".cargo"), 0o755)
	os.WriteFile(filepath.Join(outer, ".cargo", "config.toml"), []byte("[build]\nrustc-wrapper = \""+wrapper+"\"\n"), 0o644)
	os.WriteFile(filepath.Join(proj, "Cargo.toml"), []byte("[package]\nname = \"p\"\nversion = \"0.0.0\"\nedition = \"2021\"\n[workspace]\n"), 0o644)
	os.WriteFile(filepath.Join(proj, "src", "lib.rs"), []byte("pub fn f() {}\n"), 0o644)
	os.WriteFile(filepath.Join(proj, "Cargo.lock"), []byte("# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = \"p\"\nversion = \"0.0.0\"\n"), 0o644)
	extractor, _ := filepath.Abs(rust)
	errbuf := &bytes.Buffer{}
	iso := &isolationOpts{extractor: []string{extractor}, timeout: 5 * time.Minute, stderr: errbuf}
	_, err := iso.extractRustSandboxed(context.Background(), proj, []string{"--no-deps", proj})
	_, ran := os.Stat(marker)
	if ran == nil {
		t.Errorf("the rustc-wrapper of a configuration above the project ran")
	}
	// it is stopped before anything runs, and says which configuration it is
	if err == nil || !strings.Contains(err.Error(), filepath.Join(outer, ".cargo", "config.toml")) || !strings.Contains(err.Error(), "Nothing was run") {
		t.Errorf("a configuration above the project must stop the run with its name, before anything runs: %v", err)
	}
	if strings.Contains(errbuf.String(), "extracting rust under the sandbox") {
		t.Errorf("something was started although the run was to be stopped:\n%s", errbuf.String())
	}
}

// The stage that fetches has a network, so no code of the project may run in it: not a build script, not a macro. And the cargo of the
// pinned toolchain is a nightly: the unstable features that a manifest can switch on (cargo-features) are about how a package is built
// and described, and none of them may make the stage that fetches run a program or choose where it gets from. What this shows, for the features
// that this nightly accepts: with no network at all, `cargo fetch --locked` of a manifest that switches them on succeeds, a build script of a
// dependency (and a metabuild) does not run. (The -Z flags and [unstable] come from the command line, the environment and the cargo
// configuration: the stage passes no environment of the host and does not read the configuration of the project: TestSandboxFetchReadsNoConfigOfTheProject.)
func TestSandboxFetchRunsNoCodeAndAcceptsUnstableManifestFeatures(t *testing.T) {
	t.Parallel()
	if os.Getenv("RIVUS_RUST") == "" {
		skipOrFail(t, "RIVUS_RUST")
	}
	tc, err := pinnedToolchainDir()
	if err != nil {
		t.Skipf("the pinned toolchain is not there: %v", err)
	}
	manifest := `cargo-features = ["profile-rustflags", "codegen-backend", "different-binary-name", "trim-paths", "metabuild", "per-package-target", "public-dependency", "open-namespaces"]
[package]
name = "t"
version = "0.1.0"
edition = "2021"
metabuild = ["mb"]
forced-target = "x86_64-unknown-linux-gnu"
[build-dependencies]
mb = { path = "mb" }
[profile.dev]
codegen-backend = "cranelift"
rustflags = ["--cfg=x"]
trim-paths = "all"
[[bin]]
name = "t"
filename = "tt"
path = "src/main.rs"
[workspace]
`
	dir := t.TempDir()
	work := t.TempDir()
	cargoHome := t.TempDir()
	for f, body := range map[string]string{
		"Cargo.toml":    manifest,
		"Cargo.lock":    "version = 4\n\n[[package]]\nname = \"mb\"\nversion = \"0.1.0\"\n\n[[package]]\nname = \"t\"\nversion = \"0.1.0\"\ndependencies = [\n \"mb\",\n]\n",
		"src/main.rs":   "fn main(){}\n",
		"mb/Cargo.toml": "[package]\nname = \"mb\"\nversion = \"0.1.0\"\nedition = \"2021\"\n",
		"mb/src/lib.rs": "",
		// it writes to the two places that the stage may write, if it runs
		"mb/build.rs": "fn main(){ for v in [\"CARGO_HOME\", \"TMPDIR\"] { if let Ok(d) = std::env::var(v) { std::fs::write(format!(\"{}/BUILD-RAN\", d), \"x\").ok(); } } }\n",
	} {
		p := filepath.Join(dir, f)
		os.MkdirAll(filepath.Dir(p), 0o755)
		if err := os.WriteFile(p, []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	env := []string{"PATH=" + filepath.Join(tc, "bin") + ":/usr/bin:/bin", "HOME=" + work, "TMPDIR=" + work, "CARGO_HOME=" + cargoHome, "RUSTUP_TOOLCHAIN=" + pinnedToolchain}
	if sdk := sdkRoot(); sdk != "" {
		env = append(env, "SDKROOT="+sdk)
	}
	common := sandbox.Spec{Exec: []string{tc, "/Library/Developer/CommandLineTools"}, ExecFiles: sandboxPrograms, Timeout: 2 * time.Minute}
	s := fetchSpec(common, tc, dir, work, cargoHome, env)
	s.Network = false // no network at all: it must succeed all the same
	res, err := sandbox.Run(context.Background(), s)
	if err != nil {
		t.Fatalf("Run: %v", err)
	}
	if res.ExitCode != 0 {
		t.Fatalf("the fetch of a manifest with unstable features failed (no network): exit %d\n%s", res.ExitCode, res.Stderr)
	}
	for _, d := range []string{cargoHome, work} {
		if _, err := os.Stat(filepath.Join(d, "BUILD-RAN")); err == nil {
			t.Errorf("a build script ran in the stage that fetches (it wrote in %s)", d)
		}
	}
}
