// rulesWithRecord is the rules of one file with a verified_versions record (and a row, which the record does not need).
func rulesWithRecord(t *testing.T, pkg, versions string) *model.Rules {
	t.Helper()
	src := "ruleset: t@1\nverified_versions:\n  - package: " + pkg + "\n    versions: \"" + versions + "\"\n    checked: 2026-11-23\n" +
		"sinks:\n  - symbol: example.invalid/x.F\n    args: [0]\n    category: command_injection\n"
	rs, err := model.Parse(strings.NewReader(src), "t.yaml")
	if err != nil {
		t.Fatal(err)
	}
	return model.Merge(rs)
}

// What the analysis does for a language of a lock file (unverifiedFromLocks): the project in dir was read by the extractor of the
// language (no extractor is run here: it is what loadLangs records).
func unverifiedFrom(t *testing.T, lang, dir string, rules *model.Rules) []model.UnverifiedVersion {
	t.Helper()
	o := &analyzeOpts{}
	o.dir = dir
	o.lockLangs = []string{lang}
	return o.unverifiedFromLocks(rules)
}

const pubspecLock = `# Generated by pub
packages:
  dio:
    dependency: "direct main"
    description:
      name: dio
      url: "https://pub.dev"
    source: hosted
    version: "5.11.1"
  gitdep:
    dependency: "direct main"
    description:
      url: "https://example.invalid/g.git"
    source: git
    version: "0.0.1"
  localdep:
    dependency: "direct main"
    description:
      path: "../local"
    source: path
    version: "0.0.1"
sdks:
  dart: ">=3.0.0 <4.0.0"
`

func TestUnverifiedVersionsDartLock(t *testing.T) {
	dir := t.TempDir()
	write(t, filepath.Join(dir, "pubspec.lock"), pubspecLock)
	// in the range: nothing
	if got := unverifiedFrom(t, langDart, dir, rulesWithRecord(t, "dio", ">=5.11.0 <6.0.0")); len(got) != 0 {
		t.Errorf("in the range: %v", got)
	}
	// outside: one entry
	got := unverifiedFrom(t, langDart, dir, rulesWithRecord(t, "dio", ">=4.0.0 <5.0.0"))
	want := []model.UnverifiedVersion{{Package: "dio", Used: "5.11.1", Verified: []string{">=4.0.0 <5.0.0"}, Source: "pubspec.lock"}}
	if !reflect.DeepEqual(got, want) {
		t.Errorf("outside: %v, want %v", got, want)
	}
	// a git or a path dependency has no version to compare, whatever the record says
	for _, name := range []string{"gitdep", "localdep"} {
		if got := unverifiedFrom(t, langDart, dir, rulesWithRecord(t, name, ">=9.0.0 <10.0.0")); len(got) != 0 {
			t.Errorf("%s: %v", name, got)
		}
	}
	// no record for the package: nothing
	if got := unverifiedFrom(t, langDart, dir, rulesWithRecord(t, "shelf", ">=1.0.0 <2.0.0")); len(got) != 0 {
		t.Errorf("no record: %v", got)
	}
	// a pre-release is read as its numbers (the loose reading of every language)
	write(t, filepath.Join(dir, "pubspec.lock"), strings.Replace(pubspecLock, "5.11.1", "6.0.0-beta.1", 1))
	if got := unverifiedFrom(t, langDart, dir, rulesWithRecord(t, "dio", ">=5.11.0 <6.0.0")); len(got) != 1 {
		t.Errorf("a pre-release of 6.0.0 is 6.0.0: %v", got)
	}
	// no lock file: no note, no error
	if got := unverifiedFrom(t, langDart, t.TempDir(), rulesWithRecord(t, "dio", ">=4.0.0 <5.0.0")); len(got) != 0 {
		t.Errorf("no lock file: %v", got)
	}
	// a language that was not read (the run of -ir or -index): nothing
	o := &analyzeOpts{}
	o.dir = dir
	if got := o.unverifiedFromLocks(rulesWithRecord(t, "dio", ">=4.0.0 <5.0.0")); len(got) != 0 {
		t.Errorf("no language read: %v", got)
	}
}

const cargoLock = `# This file is automatically @generated by Cargo.
version = 4

[[package]]
name = "actix-web"
version = "4.9.0"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "x"

[[package]]
name = "google-cloud-storage"
version = "1.5.0"
source = "sparse+https://index.crates.io/"

[[package]]
name = "twice"
version = "1.2.0"
source = "registry+https://github.com/rust-lang/crates.io-index"

[[package]]
name = "twice"
version = "0.9.0"
source = "registry+https://github.com/rust-lang/crates.io-index"

[[package]]
name = "gitcrate"
version = "0.1.0"
source = "git+https://example.invalid/g.git?rev=abc#abc"

[[package]]
name = "app"
version = "0.1.0"
dependencies = ["actix-web"]
`

func TestUnverifiedVersionsCargoLock(t *testing.T) {
	dir := t.TempDir()
	write(t, filepath.Join(dir, "Cargo.lock"), cargoLock)
	// in the range: nothing
	if got := unverifiedFrom(t, langRust, dir, rulesWithRecord(t, "actix-web", ">=4.9.0 <5.0.0")); len(got) != 0 {
		t.Errorf("in the range: %v", got)
	}
	// outside: one entry
	got := unverifiedFrom(t, langRust, dir, rulesWithRecord(t, "actix-web", ">=3.0.0 <4.0.0"))
	want := []model.UnverifiedVersion{{Package: "actix-web", Used: "4.9.0", Verified: []string{">=3.0.0 <4.0.0"}, Source: "Cargo.lock"}}
	if !reflect.DeepEqual(got, want) {
		t.Errorf("outside: %v, want %v", got, want)
	}
	// the record spells the crate with _ and the lock with -: the same crate (the lock's spelling is reported)
	got = unverifiedFrom(t, langRust, dir, rulesWithRecord(t, "google_cloud_storage", ">=0.1.0 <1.0.0"))
	if len(got) != 1 || got[0].Package != "google-cloud-storage" || got[0].Used != "1.5.0" {
		t.Errorf("- and _: %v", got)
	}
	// several versions: one entry when any is outside, with all of them
	got = unverifiedFrom(t, langRust, dir, rulesWithRecord(t, "twice", ">=1.0.0 <2.0.0"))
	want = []model.UnverifiedVersion{{Package: "twice", Used: "0.9.0", AllUsed: []string{"1.2.0", "0.9.0"}, Verified: []string{">=1.0.0 <2.0.0"}, Source: "Cargo.lock"}}
	if !reflect.DeepEqual(got, want) {
		t.Errorf("several versions: %v, want %v", got, want)
	}
	if got := unverifiedFrom(t, langRust, dir, rulesWithRecord(t, "twice", ">=0.9.0 <2.0.0")); len(got) != 0 {
		t.Errorf("several versions, all in the range: %v", got)
	}
	// a git crate and the project's own (no source) are not listed
	for _, name := range []string{"gitcrate", "app"} {
		if got := unverifiedFrom(t, langRust, dir, rulesWithRecord(t, name, ">=9.0.0 <10.0.0")); len(got) != 0 {
			t.Errorf("%s: %v", name, got)
		}
	}
	// no lock file: no note, no error; a language that was not read: nothing
	if got := unverifiedFrom(t, langRust, t.TempDir(), rulesWithRecord(t, "actix-web", ">=3.0.0 <4.0.0")); len(got) != 0 {
		t.Errorf("no lock file: %v", got)
	}
	o := &analyzeOpts{}
	o.dir = dir
	if got := o.unverifiedFromLocks(rulesWithRecord(t, "actix-web", ">=3.0.0 <4.0.0")); len(got) != 0 {
		t.Errorf("no language read: %v", got)
	}
}
