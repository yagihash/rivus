// The generator of the skeleton of a Go package for the zoo (docs/DESIGN-package-models.md, 6.8 and 6.11, stage 2).
//
// Input: the types of the package as `go/packages` read them from the source of the fetched module (nothing of it is run), and the
// rows of the model file of the package. Output: the Go source of a skeleton module that has the real exported API of the package
// (the types with their real fields, embedding and methods, the functions, the constants and the variables), where
//
//   - a function that has a sink row records the dangerous arguments with zoo/mark (the class comes from the category of the row);
//   - a method that has a row with a flow from its receiver carries a marker of the request in an unexported field (`v`), as the
//     skeletons that were written by hand did (gin.Context), and a flow from the receiver to an argument fills the argument;
//   - every other body only returns zero values (a pointer to a struct that the skeleton has is not nil, and its embedded pointers
//     are set, so that a call through an embedded type runs).
//
// What a skeleton cannot be: a type, a field, a parameter or a result of a package that is not the standard library and not the
// module of the package (the module graph of a skeleton has no dependency but zoo). A member that needs one is left out and listed;
// a variadic parameter of such a type is dropped (the call without it is the same in both). Unexported members are not written, except
// the types that an exported signature needs, the embedded fields, and the marker `v`.
//
// The output is a function of the input only: the same package at the same version with the same rows gives the same bytes.

// GeneratedHeader is the first line of every file that the generator writes (and only of them: it is what makes a file the generator's
// to overwrite, and what keeps a hand written file safe).
const GeneratedHeader = "// Code generated by make model; DO NOT EDIT."

// skelGenVersion changes when the output of the generator changes for the same input.
const skelGenVersion = 1

// skelFile is one file of the skeleton: Dir is the directory below skel/ ("" for the root of the module).
type skelFile struct {
	Dir, Name, Content string
}

// skelResult is what the generator made.
type skelResult struct {
	Files []skelFile
	// Omitted are the members and types that were left out, with the reason (sorted).
	Omitted []string
	// RowsMissing are the rows of the model of the package that point at something the skeleton does not have (sorted). It is a
	// failure: the rows are what the skeleton is made for, and a row that is dropped silently is a row that the zoo cannot check.
	RowsMissing []string
	// Warnings are rows that the skeleton has but whose flow or record it cannot reproduce (docs/issues/164-skeleton-slice-receiver.md).
	Warnings              []string
	Funcs, Methods, Types int
}

type skelInput struct {
	Root    *types.Package
	Module  string // the module of the package (the module path of the skeleton is the same)
	Version string
	ModOf   map[string]string
	Facts   *Facts
	// UsedNames are the names that the cells and the hand written files of the skeleton use (a function, a type, a method, a field): what
	// they use is generated besides what the rows point at.
	UsedNames map[string]bool
}

type pkgOut struct {
	pkg     *types.Package
	consts  map[string]string
	vars    map[string]string
	funcs   map[string]string
	types   map[string]string
	methods map[string]map[string]string
	imports map[string]string // import path -> local name
	names   map[string]string // local name -> import path
	mark    bool              // the file calls zoo/mark
	fill    bool              // the file has zooFill
	zooV    bool              // the file has the marker of the case (zooV)
}

type skelGen struct {
	in      *skelInput
	sinks   map[string][]model.Sink // a symbol can have more than one row
	flows   map[string]model.Propagator
	carrier map[*types.TypeName]bool
	sources map[string]model.Source // call_result rows by symbol
	// srcFields are the fields that a `kind: field` source names, by type ("*": every field that can hold text)
	srcFields  map[*types.TypeName]map[string]bool
	rowSyms    map[string]bool // the symbols that the rows point at
	rowTypes   map[string]bool // the types (of the root package) that the rows point at
	rowFields  map[string]bool // the names of the fields that the rows point at
	ifaceNames map[string]bool // the methods of the interfaces that the skeleton has or that its signatures name: a type has them too
	emittedTy  []*types.TypeName
	methodDone map[*types.Func]bool
	memo       map[*types.TypeName]int // 1: in progress or fine, 2: fine, 3: not
	outs       map[string]*pkgOut
	queue      []*types.TypeName
	queued     map[*types.TypeName]bool
	emitted    map[string]bool
	omitted    map[string]bool
	res        skelResult
}

// GenerateSkeleton makes the skeleton of in.Root.
func GenerateSkeleton(in *skelInput) (*skelResult, error) {
	if in.Module == "" {
		return nil, fmt.Errorf("%s is not in a module (the standard library has no skeleton: its cells call the real package)", in.Root.Path())
	}
	g := &skelGen{in: in, sinks: map[string][]model.Sink{}, flows: map[string]model.Propagator{}, carrier: map[*types.TypeName]bool{},
		sources: map[string]model.Source{}, srcFields: map[*types.TypeName]map[string]bool{},
		memo: map[*types.TypeName]int{}, outs: map[string]*pkgOut{}, queued: map[*types.TypeName]bool{}, emitted: map[string]bool{}, omitted: map[string]bool{},
		rowSyms: map[string]bool{}, rowTypes: map[string]bool{}, rowFields: map[string]bool{}, ifaceNames: map[string]bool{"Error": true}, methodDone: map[*types.Func]bool{}}
	g.collectRows()
	if in.Facts != nil {
		for _, s := range in.Facts.SinkRows {
			g.sinks[s.Symbol] = append(g.sinks[s.Symbol], s)
		}
		for _, p := range in.Facts.FlowRows {
			g.flows[p.Symbol] = p
		}
	}
	g.markCarriers()
	root := g.out(in.Root)
	scope := in.Root.Scope()
	for _, n := range scope.Names() {
		o := scope.Lookup(n)
		if !o.Exported() {
			continue
		}
		wanted := g.in.UsedNames[n]
		switch o := o.(type) {
		case *types.Func:
			if wanted || g.rowSyms[o.FullName()] {
				g.emitFunc(root, o)
			}
		case *types.Const:
			if wanted {
				g.emitConst(root, o)
			}
		case *types.Var:
			if wanted {
				g.emitVar(root, o)
			}
		case *types.TypeName:
			if wanted || g.rowTypes[n] {
				g.want(o)
			}
		}
	}
	// the types that the signatures name bring more: the methods that satisfy an interface of the skeleton, and the types of their
	// signatures, until nothing is added
	for {
		for len(g.queue) > 0 {
			o := g.queue[0]
			g.queue = g.queue[1:]
			g.emitType(o)
		}
		added := false
		for _, o := range g.emittedTy {
			if g.emitMethods(o) {
				added = true
			}
		}
		if !added && len(g.queue) == 0 {
			break
		}
	}
	g.res.Files = g.render()
	for sym := range g.omitted {
		g.res.Omitted = append(g.res.Omitted, sym)
	}
	sort.Strings(g.res.Omitted)
	g.checkRows()
	return &g.res, nil
}

// ---- which types and members a skeleton can have

func (g *skelGen) inModule(p *types.Package) bool {
	return p != nil && g.in.ModOf[p.Path()] == g.in.Module
}

func allowedStd(p *types.Package) bool {
	s := p.Path()
	return isStdlib(s) && !strings.HasPrefix(s, "internal/") && !strings.Contains(s, "/internal/") && !strings.HasPrefix(s, "vendor/")
}

func (g *skelGen) omit(what, why string) {
	g.omitted[what+": "+why] = true
}

// typeOK says whether t can be written in the skeleton of the package cur, and adds the types of the module that it names to refs.
func (g *skelGen) typeOK(cur *types.Package, t types.Type, refs *[]*types.TypeName) bool {
	switch t := t.(type) {
	case *types.Basic:
		return true
	case *types.Named:
		return g.namedOK(cur, t.Obj(), t.TypeArgs(), refs)
	case *types.Alias:
		return g.namedOK(cur, t.Obj(), t.TypeArgs(), refs)
	case *types.TypeParam:
		return true
	case *types.Pointer:
		return g.typeOK(cur, t.Elem(), refs)
	case *types.Slice:
		return g.typeOK(cur, t.Elem(), refs)
	case *types.Array:
		return g.typeOK(cur, t.Elem(), refs)
	case *types.Chan:
		return g.typeOK(cur, t.Elem(), refs)
	case *types.Map:
		return g.typeOK(cur, t.Key(), refs) && g.typeOK(cur, t.Elem(), refs)
	case *types.Tuple:
		for i := 0; i < t.Len(); i++ {
			if !g.typeOK(cur, t.At(i).Type(), refs) {
				return false
			}
		}
		return true
	case *types.Signature:
		return g.typeOK(cur, t.Params(), refs) && g.typeOK(cur, t.Results(), refs)
	case *types.Struct:
		for i := 0; i < t.NumFields(); i++ {
			f := t.Field(i)
			if !f.Exported() && f.Pkg() != cur {
				return false
			}
			if !g.typeOK(cur, f.Type(), refs) {
				return false
			}
		}
		return true
	case *types.Interface:
		for i := 0; i < t.NumExplicitMethods(); i++ {
			m := t.ExplicitMethod(i)
			if !m.Exported() && m.Pkg() != cur {
				return false
			}
			if !g.typeOK(cur, m.Type(), refs) {
				return false
			}
		}
		for i := 0; i < t.NumEmbeddeds(); i++ {
			if !g.typeOK(cur, t.EmbeddedType(i), refs) {
				return false
			}
		}
		return true
	case *types.Union:
		for i := 0; i < t.Len(); i++ {
			if !g.typeOK(cur, t.Term(i).Type(), refs) {
				return false
			}
		}
		return true
	}
	return false
}

func (g *skelGen) namedOK(cur *types.Package, obj *types.TypeName, targs *types.TypeList, refs *[]*types.TypeName) bool {
	if obj.Pkg() == nil { // error, comparable, any
		return true
	}
	for i := 0; i < targs.Len(); i++ {
		if !g.typeOK(cur, targs.At(i), refs) {
			return false
		}
	}
	if it, ok := obj.Type().Underlying().(*types.Interface); ok {
		for i := 0; i < it.NumMethods(); i++ {
			g.ifaceNames[it.Method(i).Name()] = true
		}
	}
	switch {
	case g.inModule(obj.Pkg()):
		if obj.Pkg() != cur && !obj.Exported() {
			return false
		}
		if !g.declOK(obj) {
			return false
		}
		*refs = append(*refs, obj)
		return true
	case allowedStd(obj.Pkg()):
		return obj.Exported()
	}
	return false
}

// declOK says whether the declaration of a type of the module can be written. A struct and an interface can always (what they have that
// cannot be written is left out); the other kinds can if their underlying type can.
func (g *skelGen) declOK(obj *types.TypeName) bool {
	if st := g.memo[obj]; st != 0 {
		return st != 3
	}
	g.memo[obj] = 1
	var refs []*types.TypeName
	ok := true
	switch t := obj.Type().(type) {
	case *types.Alias:
		ok = g.tparamsOK(obj.Pkg(), t.TypeParams(), &refs) && g.typeOK(obj.Pkg(), t.Rhs(), &refs)
	case *types.Named:
		ok = g.tparamsOK(obj.Pkg(), t.TypeParams(), &refs)
		switch t.Underlying().(type) {
		case *types.Struct, *types.Interface:
		default:
			ok = ok && g.typeOK(obj.Pkg(), t.Underlying(), &refs)
		}
	}
	if ok {
		g.memo[obj] = 2
	} else {
		g.memo[obj] = 3
		g.omit(obj.Pkg().Path()+"."+obj.Name(), "the type needs a type of another module")
	}
	return ok
}

func (g *skelGen) tparamsOK(cur *types.Package, l *types.TypeParamList, refs *[]*types.TypeName) bool {
	for i := 0; i < l.Len(); i++ {
		if !g.typeOK(cur, l.At(i).Constraint(), refs) {
			return false
		}
	}
	return true
}

func (g *skelGen) want(o *types.TypeName) {
	if g.queued[o] {
		return
	}
	if !g.declOK(o) {
		return
	}
	g.queued[o] = true
	g.queue = append(g.queue, o)
}

func (g *skelGen) wantAll(refs []*types.TypeName) {
	for _, r := range refs {
		g.want(r)
	}
}

// ---- the output of a package

func (g *skelGen) out(p *types.Package) *pkgOut {
	if o := g.outs[p.Path()]; o != nil {
		return o
	}
	o := &pkgOut{pkg: p, consts: map[string]string{}, vars: map[string]string{}, funcs: map[string]string{}, types: map[string]string{},
		methods: map[string]map[string]string{}, imports: map[string]string{}, names: map[string]string{}}
	g.outs[p.Path()] = o
	return o
}

// printer writes types for one declaration of the package o, and notes which local names the text uses (a parameter must not take one
// of them when the body uses it).
type printer struct {
	o    *pkgOut
	used map[string]bool
}

func (o *pkgOut) newPrinter() *printer { return &printer{o: o, used: map[string]bool{}} }

var reservedImportNames = map[string]bool{"mark": true, "reflect": true, "zoo": true}

func (p *printer) qual(pk *types.Package) string {
	if pk.Path() == p.o.pkg.Path() {
		return ""
	}
	name, ok := p.o.imports[pk.Path()]
	if !ok {
		base := pk.Name()
		name = base
		for i := 2; p.o.names[name] != "" || reservedImportNames[name]; i++ {
			name = base + strconv.Itoa(i)
		}
		p.o.imports[pk.Path()] = name
		p.o.names[name] = pk.Path()
	}
	p.used[name] = true
	return name
}

func (p *printer) ts(t types.Type) string { return types.TypeString(t, p.qual) }

func (p *printer) tparams(l *types.TypeParamList) string {
	if l.Len() == 0 {
		return ""
	}
	var parts []string
	for i := 0; i < l.Len(); i++ {
		tp := l.At(i)
		parts = append(parts, tp.Obj().Name()+" "+p.ts(tp.Constraint()))
	}
	return "[" + strings.Join(parts, ", ") + "]"
}

// ---- constants and variables

func (g *skelGen) emitConst(o *pkgOut, c *types.Const) {
	var refs []*types.TypeName
	if !g.typeOK(o.pkg, c.Type(), &refs) {
		g.omit(o.pkg.Path()+"."+c.Name(), "the type of the constant needs a type of another module")
		return
	}
	g.wantAll(refs)
	p := o.newPrinter()
	val := c.Val()
	text := val.ExactString()
	if val.Kind() == constant.Float {
		text = val.String()
	}
	if b, ok := c.Type().(*types.Basic); ok && b.Info()&types.IsUntyped != 0 {
		o.consts[c.Name()] = "const " + c.Name() + " = " + text
		return
	}
	o.consts[c.Name()] = "const " + c.Name() + " " + p.ts(c.Type()) + " = " + text
}

func (g *skelGen) emitVar(o *pkgOut, v *types.Var) {
	var refs []*types.TypeName
	if !g.typeOK(o.pkg, v.Type(), &refs) {
		g.omit(o.pkg.Path()+"."+v.Name(), "the type of the variable needs a type of another module")
		return
	}
	g.wantAll(refs)
	p := o.newPrinter()
	if n, ok := v.Type().(*types.Named); ok && n.Obj().Pkg() == nil && n.Obj().Name() == "error" {
		// an error that is a value of the package (ErrNoRows) is a distinct value, so that errors.Is tells it from another
		o.vars[v.Name()] = "var " + v.Name() + " = " + p.qualName("errors") + ".New(" + strconv.Quote(v.Name()) + ")"
		return
	}
	o.vars[v.Name()] = "var " + v.Name() + " " + p.ts(v.Type())
}

// qualName names a standard package that the generator itself uses.
func (p *printer) qualName(pkgPath string) string {
	name := path.Base(pkgPath)
	got, ok := p.o.imports[pkgPath]
	if !ok {
		got = name
		for i := 2; p.o.names[got] != "" || reservedImportNames[got]; i++ {
			got = name + strconv.Itoa(i)
		}
		p.o.imports[pkgPath] = got
		p.o.names[got] = pkgPath
	}
	p.used[got] = true
	return got
}

// ---- types

func (g *skelGen) emitType(obj *types.TypeName) {
	o := g.out(obj.Pkg())
	p := o.newPrinter()
	name := obj.Name()
	switch t := obj.Type().(type) {
	case *types.Alias:
		var refs []*types.TypeName
		g.typeOK(obj.Pkg(), t.Rhs(), &refs)
		g.wantAll(refs)
		o.types[name] = "type " + name + p.tparams(t.TypeParams()) + " = " + p.ts(t.Rhs())
		g.res.Types++
	case *types.Named:
		var refs []*types.TypeName
		g.tparamsOK(obj.Pkg(), t.TypeParams(), &refs)
		head := "type " + name + p.tparams(t.TypeParams()) + " "
		switch u := t.Underlying().(type) {
		case *types.Struct:
			o.types[name] = head + g.structText(p, obj, u, &refs)
		case *types.Interface:
			o.types[name] = head + g.interfaceText(p, obj, u, &refs)
		default:
			g.typeOK(obj.Pkg(), u, &refs)
			o.types[name] = head + p.ts(u)
		}
		g.wantAll(refs)
		g.res.Types++
		g.emittedTy = append(g.emittedTy, obj)
		g.emitMethods(obj)
	}
}

// emitMethods writes the methods of a type that the skeleton needs: the ones that a row points at, the ones that the cells use, and the
// ones that an interface of the skeleton has (so that the type satisfies it as the real type does). It says whether it wrote one.
func (g *skelGen) emitMethods(obj *types.TypeName) bool {
	t, ok := obj.Type().(*types.Named)
	if !ok {
		return false
	}
	var ms []*types.Func
	for i := 0; i < t.NumMethods(); i++ {
		m := t.Method(i)
		if m.Exported() && !g.methodDone[m] && (g.rowSyms[m.FullName()] || g.in.UsedNames[m.Name()] || g.ifaceNames[m.Name()]) {
			ms = append(ms, m)
		}
	}
	sort.Slice(ms, func(i, j int) bool { return ms[i].Name() < ms[j].Name() })
	for _, m := range ms {
		g.methodDone[m] = true
		g.emitFunc(g.out(obj.Pkg()), m)
	}
	return len(ms) > 0
}

// noteType records the type that a row points at (a method or a field is cut off from its name). It is a method, not a closure
// that is handed around: rivus reads its own code (TestDogfood) and does not follow a captured value into a helper.
func (g *skelGen) noteType(name string) {
	if i := strings.IndexAny(name, "."); i > 0 {
		name = name[:i]
	}
	g.rowTypes[name] = true
}

// noteSym records the symbol of a row, and the type of its receiver when that type is in the package.
func (g *skelGen) noteSym(prefix, s string) {
	g.rowSyms[s] = true
	if rt := receiverType(s); strings.HasPrefix(rt, prefix) {
		g.noteType(strings.TrimPrefix(rt, prefix))
	}
}

// collectRows reads what the rows of the package point at.
func (g *skelGen) collectRows() {
	f := g.in.Facts
	if f == nil {
		return
	}
	prefix := g.in.Root.Path() + "."
	for _, r := range f.SinkRows {
		g.noteSym(prefix, r.Symbol)
		for _, p := range r.PartList() {
			if p.Field != "" {
				g.rowFields[strings.Split(p.Field, ".")[0]] = true
			}
		}
	}
	for _, r := range f.FlowRows {
		g.noteSym(prefix, r.Symbol)
	}
	for _, r := range f.SourceRows {
		switch {
		case r.Symbol != "":
			g.noteSym(prefix, r.Symbol)
		case r.Field != "" && strings.HasPrefix(r.Field, prefix):
			rest := strings.TrimPrefix(r.Field, prefix)
			g.noteType(rest)
			if _, fld, ok := strings.Cut(rest, "."); ok {
				g.rowFields[fld] = true
			}
		case r.Type != "":
			if t := strings.TrimPrefix(r.Type, "*"); strings.HasPrefix(t, prefix) {
				g.noteType(strings.TrimPrefix(t, prefix))
			}
		}
	}
}

// checkRows fails the generation for a row that points at something the skeleton does not have, and lists the rows that the skeleton
// has but cannot carry out (a flow from a receiver that cannot hold the marker, a sink that records nothing).
func (g *skelGen) checkRows() {
	f := g.in.Facts
	if f == nil {
		return
	}
	prefix := g.in.Root.Path() + "."
	missing := map[string]bool{}
	for _, r := range f.SinkRows {
		if !g.emitted[r.Symbol] {
			missing[r.Symbol] = true
		}
	}
	for _, r := range f.FlowRows {
		if !g.emitted[r.Symbol] {
			missing[r.Symbol] = true
		}
	}
	for _, r := range f.SourceRows {
		switch {
		case r.Symbol != "":
			if !g.emitted[r.Symbol] {
				missing[r.Symbol] = true
			}
		case r.Field != "" && strings.HasPrefix(r.Field, prefix):
			typName, fld, ok := strings.Cut(strings.TrimPrefix(r.Field, prefix), ".")
			tn, _ := g.in.Root.Scope().Lookup(typName).(*types.TypeName)
			if !ok || tn == nil || !g.queued[tn] {
				missing[r.Field] = true
				continue
			}
			if st, isStruct := tn.Type().Underlying().(*types.Struct); isStruct && fld != "*" {
				found := false
				for i := 0; i < st.NumFields(); i++ {
					if st.Field(i).Name() == fld && g.keepField(g.in.Root, st.Field(i)) {
						found = true
					}
				}
				if !found {
					missing[r.Field] = true
				}
			}
		case r.Type != "":
			t := strings.TrimPrefix(r.Type, "*")
			if strings.HasPrefix(t, prefix) {
				tn, _ := g.in.Root.Scope().Lookup(strings.TrimPrefix(t, prefix)).(*types.TypeName)
				if tn == nil || !g.queued[tn] {
					missing[r.Type] = true
				}
			}
		}
	}
	for s := range missing {
		g.res.RowsMissing = append(g.res.RowsMissing, s)
	}
	sort.Strings(g.res.RowsMissing)
	for k := range g.omitted {
		if strings.Contains(k, "the flow from the receiver is not reproduced") || strings.Contains(k, "records nothing") {
			g.res.Warnings = append(g.res.Warnings, k)
		}
	}
	sort.Strings(g.res.Warnings)
}

// keepField says whether the skeleton has the field of a struct of its own module (or the standard library): an embedded field (the
// embedding is part of the shape), a field that a row or the cells use, and a field whose type brings no other type of the module (so it
// costs a line and no closure).
func (g *skelGen) keepField(cur *types.Package, f *types.Var) bool {
	if !f.Embedded() && !f.Exported() {
		return false
	}
	if f.Embedded() && !f.Exported() && f.Pkg() != cur {
		return false
	}
	var refs []*types.TypeName
	if !g.typeOK(cur, f.Type(), &refs) {
		return false
	}
	return f.Embedded() || g.rowFields[f.Name()] || g.in.UsedNames[f.Name()] || len(refs) == 0
}

func (g *skelGen) structText(p *printer, obj *types.TypeName, s *types.Struct, refs *[]*types.TypeName) string {
	var b strings.Builder
	b.WriteString("struct {\n")
	for i := 0; i < s.NumFields(); i++ {
		f := s.Field(i)
		if !g.keepField(obj.Pkg(), f) {
			if f.Exported() || f.Embedded() {
				g.omit(obj.Pkg().Path()+"."+obj.Name()+"."+f.Name(), "the field needs a type of another module")
			}
			continue
		}
		g.typeOK(obj.Pkg(), f.Type(), refs)
		if f.Embedded() {
			b.WriteString("\t" + p.ts(f.Type()) + "\n")
		} else {
			b.WriteString("\t" + f.Name() + " " + p.ts(f.Type()) + "\n")
		}
	}
	if g.carrier[obj] {
		b.WriteString("\tv string // the marker of what the receiver stands for (a request): the getters return it\n")
	}
	b.WriteString("}")
	return b.String()
}

func (g *skelGen) interfaceText(p *printer, obj *types.TypeName, it *types.Interface, refs *[]*types.TypeName) string {
	var b strings.Builder
	b.WriteString("interface {\n")
	for i := 0; i < it.NumEmbeddeds(); i++ {
		e := it.EmbeddedType(i)
		var r []*types.TypeName
		if !g.typeOK(obj.Pkg(), e, &r) {
			g.omit(obj.Pkg().Path()+"."+obj.Name(), "an embedded interface needs a type of another module")
			continue
		}
		*refs = append(*refs, r...)
		b.WriteString("\t" + p.ts(e) + "\n")
	}
	for i := 0; i < it.NumExplicitMethods(); i++ {
		m := it.ExplicitMethod(i)
		if !m.Exported() {
			continue
		}
		sig := m.Type().(*types.Signature)
		var r []*types.TypeName
		if !g.typeOK(obj.Pkg(), sig, &r) {
			g.omit(obj.Pkg().Path()+"."+obj.Name()+"."+m.Name(), "the method needs a type of another module")
			continue
		}
		*refs = append(*refs, r...)
		b.WriteString("\t" + m.Name() + p.sigText(sig, false) + "\n")
		g.emitted["("+obj.Pkg().Path()+"."+obj.Name()+")."+m.Name()] = true
	}
	b.WriteString("}")
	return b.String()
}

// sigText writes the parameters and the results of a signature without names (`(string, ...int) error`).
func (p *printer) sigText(sig *types.Signature, _ bool) string {
	var ps []string
	for i := 0; i < sig.Params().Len(); i++ {
		t := sig.Params().At(i).Type()
		if sig.Variadic() && i == sig.Params().Len()-1 {
			ps = append(ps, "..."+p.ts(t.(*types.Slice).Elem()))
		} else {
			ps = append(ps, p.ts(t))
		}
	}
	s := "(" + strings.Join(ps, ", ") + ")"
	switch sig.Results().Len() {
	case 0:
	case 1:
		s += " " + p.ts(sig.Results().At(0).Type())
	default:
		var rs []string
		for i := 0; i < sig.Results().Len(); i++ {
			rs = append(rs, p.ts(sig.Results().At(i).Type()))
		}
		s += " (" + strings.Join(rs, ", ") + ")"
	}
	return s
}

// ---- functions and methods

type skelParam struct {
	orig     int // the position in the real signature
	name     string
	t        types.Type
	variadic bool
}

func (g *skelGen) emitFunc(o *pkgOut, fn *types.Func) {
	sig := fn.Type().(*types.Signature)
	cur := o.pkg
	full := fn.FullName()
	what := full
	var refs []*types.TypeName
	if !g.tparamsOK(cur, sig.TypeParams(), &refs) {
		g.omit(what, "a type parameter needs a type of another module")
		return
	}
	var ps []skelParam
	for i := 0; i < sig.Params().Len(); i++ {
		v := sig.Params().At(i)
		variadic := sig.Variadic() && i == sig.Params().Len()-1
		chk := v.Type()
		if variadic {
			chk = chk.(*types.Slice).Elem()
		}
		if !g.typeOK(cur, chk, &refs) {
			if variadic {
				g.omit(what, "the variadic parameter "+v.Name()+" is dropped (its type is of another module)")
				continue
			}
			g.omit(what, "the parameter "+v.Name()+" needs a type of another module")
			return
		}
		ps = append(ps, skelParam{orig: i, name: v.Name(), t: v.Type(), variadic: variadic})
	}
	var results []types.Type
	for i := 0; i < sig.Results().Len(); i++ {
		t := sig.Results().At(i).Type()
		if !g.typeOK(cur, t, &refs) {
			g.omit(what, "a result needs a type of another module")
			return
		}
		results = append(results, t)
	}
	var recv *types.Var
	var recvPtr bool
	var recvNamed *types.Named
	if sig.Recv() != nil {
		recv = sig.Recv()
		rt := recv.Type()
		if pt, ok := rt.(*types.Pointer); ok {
			recvPtr = true
			rt = pt.Elem()
		}
		recvNamed, _ = types.Unalias(rt).(*types.Named)
		if recvNamed == nil {
			g.omit(what, "the receiver is not a named type")
			return
		}
	}
	g.wantAll(refs)

	// the names: a parameter must not be named like a package that the body writes
	rename := map[string]bool{}
	var text string
	for round := 0; round < 4; round++ {
		var bodyUsed map[string]bool
		text, bodyUsed = g.funcText(o, fn, sig, recv, recvPtr, recvNamed, ps, results, rename)
		clash := false
		for _, p := range ps {
			if bodyUsed[p.name] && !rename[p.name] {
				rename[p.name] = true
				clash = true
			}
		}
		if rn := recvName(recv); bodyUsed[rn] && !rename[rn] {
			rename[rn] = true
			clash = true
		}
		if !clash {
			break
		}
	}
	if recv == nil {
		o.funcs[fn.Name()] = text
		g.res.Funcs++
	} else {
		m := o.methods[recvNamed.Obj().Name()]
		if m == nil {
			m = map[string]string{}
			o.methods[recvNamed.Obj().Name()] = m
		}
		m[fn.Name()] = text
		g.res.Methods++
	}
	g.emitted[full] = true
}

func recvName(recv *types.Var) string {
	if recv == nil {
		return ""
	}
	if n := recv.Name(); n != "" && n != "_" {
		return n
	}
	return "r"
}

func (g *skelGen) funcText(o *pkgOut, fn *types.Func, sig *types.Signature, recv *types.Var, recvPtr bool, recvNamed *types.Named,
	ps []skelParam, results []types.Type, rename map[string]bool) (string, map[string]bool) {
	p := o.newPrinter() // for the signature (it never clashes with a parameter name)
	b := o.newPrinter() // for the body
	// names: the real ones, a number for the ones that have none, and a `_` after a name that the body would shadow
	taken := map[string]bool{}
	rn := ""
	if recv != nil {
		rn = recvName(recv)
		if rename[rn] {
			rn += "_"
		}
		taken[rn] = true
	}
	qs := make([]skelParam, len(ps))
	for i, q := range ps {
		n := q.name
		if n == "" || n == "_" {
			n = "p" + strconv.Itoa(i)
		}
		if rename[n] {
			n += "_"
		}
		for taken[n] {
			n += "_"
		}
		taken[n] = true
		q.name = n
		qs[i] = q
	}
	ps = qs
	var sb strings.Builder
	sb.WriteString("func ")
	if recv != nil {
		rt := recvNamed.Obj().Name()
		if tp := recvNamed.TypeParams(); tp.Len() > 0 {
			var ns []string
			for i := 0; i < sig.RecvTypeParams().Len(); i++ {
				ns = append(ns, sig.RecvTypeParams().At(i).Obj().Name())
			}
			rt += "[" + strings.Join(ns, ", ") + "]"
		}
		if recvPtr {
			rt = "*" + rt
		}
		sb.WriteString("(" + rn + " " + rt + ") ")
	}
	sb.WriteString(fn.Name() + p.tparams(sig.TypeParams()))
	var pt []string
	for _, q := range ps {
		if q.variadic {
			pt = append(pt, q.name+" ..."+p.ts(q.t.(*types.Slice).Elem()))
		} else {
			pt = append(pt, q.name+" "+p.ts(q.t))
		}
	}
	sb.WriteString("(" + strings.Join(pt, ", ") + ")")
	switch len(results) {
	case 0:
	case 1:
		sb.WriteString(" " + p.ts(results[0]))
	default:
		var rs []string
		for _, r := range results {
			rs = append(rs, p.ts(r))
		}
		sb.WriteString(" (" + strings.Join(rs, ", ") + ")")
	}
	sb.WriteString(" {\n")
	var body []string
	body = append(body, g.recordLines(o, b, fn.FullName(), sig, recv, rn, ps)...)
	flowLines, exprs := g.flowBody(o, b, fn.FullName(), recvNamed, rn, ps, results)
	body = append(body, flowLines...)
	if len(results) > 0 {
		body = append(body, "return "+strings.Join(exprs, ", "))
	}
	for _, l := range body {
		sb.WriteString("\t" + l + "\n")
	}
	sb.WriteString("}")
	used := b.used
	if len(body) > 0 && strings.Contains(strings.Join(body, "\n"), "mark.") {
		o.mark = true
		used["mark"] = true
	}
	return sb.String(), used
}

// ---- sink rows: the record of the dangerous arguments

var categoryClass = map[string]string{
	"sql_injection":     "SinkSQL",
	"command_injection": "SinkCmd",
	"resource_name":     "SinkCmd",
	"xss":               "SinkHTML",
}

func stringKind(t types.Type) (isString, isBytes bool) {
	switch u := t.Underlying().(type) {
	case *types.Basic:
		return u.Kind() == types.String, false
	case *types.Slice:
		if b, ok := u.Elem().Underlying().(*types.Basic); ok && b.Kind() == types.Byte {
			return false, true
		}
	}
	return false, false
}

func isInterface(t types.Type) bool {
	_, ok := t.Underlying().(*types.Interface)
	return ok
}

// recordCall makes the statement that records the value of the expression e of the type t for a sink of the category.
func recordCall(category, e string, t types.Type, b *printer) []string {
	fn := categoryClass[category]
	is, isb := stringKind(t)
	str := e
	switch {
	case is:
		if bt, ok := t.(*types.Basic); !ok || bt.Kind() != types.String {
			str = "string(" + e + ")"
		}
	case isb:
		if fn == "SinkCmd" {
			return []string{"mark.SinkCmdBytes(" + e + ")"}
		}
		str = "string(" + e + ")"
	case isInterface(t):
		return []string{"mark.SinkAny(" + e + ")"}
	default:
		if s, ok := t.Underlying().(*types.Slice); ok {
			if es, _ := stringKind(s.Elem()); es {
				return []string{"for _, s := range " + e + " {", "\t" + recordStr(category, "string(s)"), "}"}
			}
		}
		return nil
	}
	return []string{recordStr(category, str)}
}

func recordStr(category, s string) string {
	switch {
	case categoryClass[category] != "":
		return "mark." + categoryClass[category] + "(" + s + ")"
	case category == "path_traversal":
		return `mark.SinkPath("/zoo/base", ` + s + ")"
	}
	return "mark.SinkAny(" + s + ")"
}

func (g *skelGen) recordLines(o *pkgOut, b *printer, full string, sig *types.Signature, recv *types.Var, rn string, ps []skelParam) []string {
	var lines []string
	for _, row := range g.sinks[full] {
		l := g.recordRow(row, sig, recv, rn, ps, b)
		if len(l) == 0 {
			g.omit(full, "a sink row that records nothing (no dangerous position has a type that the skeleton can record)")
		}
		lines = append(lines, l...)
	}
	return lines
}

func (g *skelGen) recordRow(row model.Sink, sig *types.Signature, recv *types.Var, rn string, ps []skelParam, b *printer) []string {
	byOrig := map[int]skelParam{}
	for _, q := range ps {
		byOrig[q.orig] = q
	}
	var lines []string
	order := row.WholeArgs(sig.Params().Len())
	for _, a := range order {
		q, ok := byOrig[a]
		if !ok {
			continue
		}
		if q.variadic {
			elem := q.t.(*types.Slice).Elem()
			if es, _ := stringKind(elem); es {
				lines = append(lines, "for _, s := range "+q.name+" {", "\t"+recordStr(row.Category, "s"), "}")
			} else if isInterface(elem) {
				lines = append(lines, "for _, s := range "+q.name+" {", "\tmark.SinkAny(s)", "}")
			}
			continue
		}
		lines = append(lines, recordCall(row.Category, q.name, q.t, b)...)
	}
	if row.WholeRecv() && recv != nil {
		lines = append(lines, recordCall(row.Category, rn, recv.Type(), b)...)
	}
	for _, part := range row.PartList() {
		if part.Arg == nil || strings.Contains(part.Field, "[]") {
			continue
		}
		q, ok := byOrig[*part.Arg]
		if !ok {
			continue
		}
		expr, ft := q.name, q.t
		good := true
		var guards []string
		for _, f := range strings.Split(part.Field, ".") {
			if isPointer(ft) {
				guards = append(guards, expr+" != nil")
			}
			ft = derefType(ft)
			st, ok := ft.Underlying().(*types.Struct)
			if !ok {
				good = false
				break
			}
			var found *types.Var
			for i := 0; i < st.NumFields(); i++ {
				if st.Field(i).Name() == f {
					found = st.Field(i)
				}
			}
			if found == nil {
				good = false
				break
			}
			expr += "." + f
			ft = found.Type()
		}
		if good {
			rec := recordCall(row.Category, expr, ft, b)
			if len(rec) > 0 && len(guards) > 0 {
				lines = append(lines, "if "+strings.Join(guards, " && ")+" {")
				for _, l := range rec {
					lines = append(lines, "\t"+l)
				}
				lines = append(lines, "}")
			} else {
				lines = append(lines, rec...)
			}
		}
	}
	return lines
}

func derefType(t types.Type) types.Type {
	if p, ok := t.(*types.Pointer); ok {
		return p.Elem()
	}
	if p, ok := t.Underlying().(*types.Pointer); ok {
		return p.Elem()
	}
	return t
}

// ---- flows: what a getter returns, and what a binder fills

// rootStruct finds the struct type of the root package that the name (`Type`) says.
func (g *skelGen) rootStruct(name string) *types.TypeName {
	tn, ok := g.in.Root.Scope().Lookup(name).(*types.TypeName)
	if !ok {
		return nil
	}
	if _, isStruct := tn.Type().Underlying().(*types.Struct); !isStruct {
		return nil
	}
	return tn
}

// markCarriers finds the structs that need the marker `v`: the receiver of a method with a flow from the receiver. It also reads the
// sources: what a `call_result` source returns is the marker of the case (zooV, which a hand written constructor sets), and a struct
// that a `field` source names is made by the functions that return it with the marker in those fields.
func (g *skelGen) markCarriers() {
	if g.in.Facts == nil {
		return
	}
	prefix := g.in.Root.Path() + "."
	for _, r := range g.in.Facts.FlowRows {
		hasRecv := false
		for _, f := range r.Flows {
			if f.From == "recv" {
				hasRecv = true
			}
		}
		if !hasRecv {
			continue
		}
		if rt := receiverType(r.Symbol); strings.HasPrefix(rt, prefix) {
			if tn := g.rootStruct(strings.TrimPrefix(rt, prefix)); tn != nil {
				g.carrier[tn] = true
			}
		}
	}
	for _, sr := range g.in.Facts.SourceRows {
		switch {
		case sr.Kind == "call_result" && sr.Symbol != "":
			g.sources[sr.Symbol] = sr
		case sr.Kind == "field" && strings.HasPrefix(sr.Field, prefix):
			typ, field, ok := strings.Cut(strings.TrimPrefix(sr.Field, prefix), ".")
			if !ok {
				continue
			}
			if tn := g.rootStruct(typ); tn != nil {
				if g.srcFields[tn] == nil {
					g.srcFields[tn] = map[string]bool{}
				}
				g.srcFields[tn][field] = true
			}
		}
	}
}

// ctorExpr is the value of a type that carries the marker of the case, for a result of that type: `&Issue{v: zooV, Title: &zooV}`
// (a slice of them has one element). It says no for a type that is not a carrier of the package.
func (g *skelGen) ctorExpr(b *printer, t types.Type) (string, bool) {
	switch u := t.(type) {
	case *types.Pointer:
		if e, ok := g.ctorLit(b, u.Elem()); ok {
			return "&" + e, true
		}
	case *types.Slice:
		if p, ok := u.Elem().(*types.Pointer); ok {
			if e, ok := g.ctorLit(b, p.Elem()); ok {
				return b.ts(t) + "{" + strings.TrimPrefix(e, b.ts(p.Elem())) + "}", true
			}
		}
	}
	return "", false
}

func (g *skelGen) ctorLit(b *printer, t types.Type) (string, bool) {
	n, ok := t.(*types.Named)
	if !ok || n.Obj().Pkg() == nil || n.Obj().Pkg().Path() != g.in.Root.Path() || len(g.srcFields[n.Obj()]) == 0 || n.TypeParams().Len() > 0 {
		return "", false
	}
	st, ok := n.Underlying().(*types.Struct)
	if !ok {
		return "", false
	}
	root := g.out(g.in.Root)
	var fields []string
	for i := 0; i < st.NumFields(); i++ {
		f := st.Field(i)
		if !f.Exported() || f.Embedded() || !g.keepField(g.in.Root, f) {
			continue
		}
		if sf := g.srcFields[n.Obj()]; !sf[f.Name()] && !sf["*"] {
			continue
		}
		if e, ok := carryExpr(g, b, f.Type(), "zooV", 1, false); ok {
			fields = append(fields, f.Name()+": "+e)
		}
	}
	root.zooV = true
	return b.ts(t) + "{" + strings.Join(fields, ", ") + "}", true
}

// flowBody returns the statements that the flows of the row make, and the expressions that the function returns.
func (g *skelGen) flowBody(o *pkgOut, b *printer, full string, recvNamed *types.Named, rn string, ps []skelParam, results []types.Type) ([]string, []string) {
	exprs := make([]string, len(results))
	row, hasRow := g.flows[full]
	src, isSource := g.sources[full]
	_ = src
	carrier := ""
	if hasRow && recvNamed != nil && g.carrier[recvNamed.Obj()] {
		carrier = rn + ".v"
	}
	var lines []string
	byOrig := map[int]skelParam{}
	for _, q := range ps {
		byOrig[q.orig] = q
	}
	if hasRow {
		for _, f := range row.Flows {
			if f.From == "recv" && carrier != "" && strings.HasPrefix(f.To, "arg") {
				if i, err := strconv.Atoi(strings.TrimPrefix(f.To, "arg")); err == nil {
					if q, ok := byOrig[i]; ok && !q.variadic && (isInterface(q.t) || isPointer(q.t)) {
						lines = append(lines, "zooFill("+q.name+", "+carrier+")")
						o.fill = true
					}
				}
			}
		}
		for ri := range results {
			for _, f := range row.Flows {
				if !flowsToResult(f.To, ri, len(results)) || exprs[ri] != "" {
					continue
				}
				switch {
				case f.From == "recv" && carrier != "":
					if e, ok := carryExpr(g, b, results[ri], carrier, 0, true); ok {
						exprs[ri] = e
					}
				case strings.HasPrefix(f.From, "arg"):
					i, err := strconv.Atoi(strings.TrimPrefix(f.From, "arg"))
					if q, ok := byOrig[i]; err == nil && ok && !q.variadic && types.Identical(q.t, results[ri]) && !isErrorType(results[ri]) {
						exprs[ri] = q.name
					}
				}
			}
		}
	}
	if isSource {
		// what the call returns is what a user of the service wrote: the marker of the receiver (an accessor of a value), or of the case
		marker := "zooV"
		g.out(g.in.Root).zooV = true
		for ri := range results {
			if exprs[ri] == "" {
				if e, ok := carryExpr(g, b, results[ri], marker, 0, false); ok {
					exprs[ri] = e
				}
			}
		}
	}
	recvFlow := false
	if hasRow {
		for _, f := range row.Flows {
			recvFlow = recvFlow || f.From == "recv"
		}
	}
	if recvFlow && carrier == "" {
		g.omit(full, "the flow from the receiver is not reproduced (the receiver is not a struct of the skeleton: a slice, a map)")
	}
	for ri, t := range results {
		if exprs[ri] == "" {
			if e, ok := g.ctorExpr(b, t); ok {
				exprs[ri] = e
			} else if bt, ok := t.(*types.Basic); ok && bt.Kind() == types.Bool && carrier != "" && recvFlow {
				exprs[ri] = "true" // the flag that says a value was found, next to the text that the getter returns
			} else {
				exprs[ri] = g.zeroExpr(b, t, 0)
			}
		}
	}
	return lines, exprs
}

func isPointer(t types.Type) bool {
	_, ok := t.Underlying().(*types.Pointer)
	return ok
}

func isErrorType(t types.Type) bool {
	n, ok := t.(*types.Named)
	return ok && n.Obj().Pkg() == nil && n.Obj().Name() == "error"
}

func flowsToResult(to string, i, n int) bool {
	if to == "result" {
		return true
	}
	if strings.HasPrefix(to, "result") {
		k, err := strconv.Atoi(strings.TrimPrefix(to, "result"))
		return err == nil && k == i
	}
	return false
}

// carryExpr is a value of the type t that has the marker c in every place that takes text.
func carryExpr(g *skelGen, b *printer, t types.Type, c string, depth int, top bool) (string, bool) {
	switch u := t.Underlying().(type) {
	case *types.Basic:
		switch {
		case u.Kind() == types.String:
			if bt, ok := t.(*types.Basic); ok && bt.Kind() == types.String {
				return c, true
			}
			return b.ts(t) + "(" + c + ")", true
		case u.Kind() == types.Bool && top:
			return "true", true
		}
	case *types.Slice:
		if eb, ok := u.Elem().Underlying().(*types.Basic); ok && eb.Kind() == types.Byte {
			return b.ts(t) + "(" + c + ")", true
		}
		if e, ok := carryExpr(g, b, u.Elem(), c, depth, false); ok {
			return b.ts(t) + "{" + e + "}", true
		}
	case *types.Map:
		if kb, ok := u.Key().Underlying().(*types.Basic); ok && kb.Kind() == types.String {
			if e, ok := carryExpr(g, b, u.Elem(), c, depth, false); ok {
				k := `"zoo"`
				if kt, ok := u.Key().(*types.Basic); !ok || kt.Kind() != types.String {
					k = b.ts(u.Key()) + `("zoo")`
				}
				return b.ts(t) + "{" + k + ": " + e + "}", true
			}
		}
	case *types.Pointer:
		if eb, ok := u.Elem().(*types.Basic); ok && eb.Kind() == types.String {
			return "&" + c, true
		}
		if st, ok := u.Elem().Underlying().(*types.Struct); ok && depth < 2 {
			if e, ok := carryStruct(g, b, u.Elem(), st, c, depth); ok {
				return "&" + e, true
			}
		}
	case *types.Interface:
		if n, ok := t.(*types.Named); ok && n.Obj().Pkg() != nil && n.Obj().Pkg().Path() == "io" {
			switch n.Obj().Name() {
			case "Reader":
				return b.qualName("strings") + ".NewReader(" + c + ")", true
			case "ReadCloser":
				return b.qualName("io") + ".NopCloser(" + b.qualName("strings") + ".NewReader(" + c + "))", true
			}
		}
	case *types.Struct:
		if depth < 2 {
			return carryStruct(g, b, t, u, c, depth)
		}
	}
	return "", false
}

func carryStruct(g *skelGen, b *printer, t types.Type, st *types.Struct, c string, depth int) (string, bool) {
	var fields []string
	n, _ := types.Unalias(t).(*types.Named)
	for i := 0; i < st.NumFields(); i++ {
		f := st.Field(i)
		if !f.Exported() || f.Embedded() {
			continue
		}
		if n != nil && g.inModule(n.Obj().Pkg()) && !g.keepField(n.Obj().Pkg(), f) {
			continue
		}
		if e, ok := carryExpr(g, b, f.Type(), c, depth+1, false); ok {
			fields = append(fields, f.Name()+": "+e)
		}
	}
	if len(fields) == 0 {
		return "", false
	}
	return b.ts(t) + "{" + strings.Join(fields, ", ") + "}", true
}

// zeroExpr is the value that a function returns where no flow says otherwise: the zero value, except that a pointer to a struct is
// not nil (a call on it runs), and the embedded pointers of that struct are set the same way.
func (g *skelGen) zeroExpr(b *printer, t types.Type, depth int) string {
	switch u := t.Underlying().(type) {
	case *types.Basic:
		switch {
		case u.Kind() == types.String:
			return `""`
		case u.Kind() == types.Bool:
			return "false"
		case u.Kind() == types.UnsafePointer || u.Kind() == types.UntypedNil:
			return "nil"
		}
		if tt, ok := t.(*types.Basic); ok && tt == u {
			return "0"
		}
		return b.ts(t) + "(0)"
	case *types.Interface, *types.Slice, *types.Map, *types.Signature, *types.Chan:
		if _, ok := t.(*types.TypeParam); ok {
			return "*new(" + b.ts(t) + ")"
		}
		return "nil"
	case *types.Pointer:
		if st, ok := u.Elem().Underlying().(*types.Struct); ok && depth < 2 {
			if _, tp := u.Elem().(*types.TypeParam); !tp {
				return "&" + b.ts(u.Elem()) + "{" + g.embeddedInit(b, u.Elem(), st, depth) + "}"
			}
		}
		return "nil"
	case *types.Struct:
		if _, tp := t.(*types.TypeParam); !tp {
			return b.ts(t) + "{}"
		}
	}
	return "*new(" + b.ts(t) + ")"
}

// embeddedInit sets the embedded pointers of a struct of the skeleton (`DB: &sql.DB{}`).
func (g *skelGen) embeddedInit(b *printer, t types.Type, st *types.Struct, depth int) string {
	n, ok := types.Unalias(t).(*types.Named)
	if !ok || !g.inModule(n.Obj().Pkg()) {
		return ""
	}
	var parts []string
	for i := 0; i < st.NumFields(); i++ {
		f := st.Field(i)
		if !f.Embedded() || !g.keepField(n.Obj().Pkg(), f) {
			continue
		}
		if f.Pkg() != nil && !f.Exported() && f.Pkg() != b.o.pkg {
			continue
		}
		if _, isPtr := f.Type().(*types.Pointer); !isPtr {
			continue
		}
		parts = append(parts, f.Name()+": "+g.zeroExpr(b, f.Type(), depth+1))
	}
	return strings.Join(parts, ", ")
}

// ---- the files

func (g *skelGen) render() []skelFile {
	var paths []string
	for p := range g.outs {
		paths = append(paths, p)
	}
	sort.Strings(paths)
	var files []skelFile
	for _, pp := range paths {
		o := g.outs[pp]
		dir := strings.TrimPrefix(strings.TrimPrefix(pp, g.in.Module), "/")
		var body strings.Builder
		sect := func(m map[string]string) {
			var ks []string
			for k := range m {
				ks = append(ks, k)
			}
			sort.Strings(ks)
			for _, k := range ks {
				body.WriteString(m[k] + "\n\n")
			}
		}
		sect(o.consts)
		sect(o.vars)
		var tn []string
		for k := range o.types {
			tn = append(tn, k)
		}
		for k := range o.methods {
			if _, ok := o.types[k]; !ok {
				tn = append(tn, k)
			}
		}
		sort.Strings(tn)
		for _, k := range tn {
			if t, ok := o.types[k]; ok {
				body.WriteString(t + "\n\n")
			}
			sect(o.methods[k])
		}
		sect(o.funcs)
		if o.fill {
			body.WriteString(fillHelper + "\n")
		}
		if o.zooV {
			body.WriteString(zooVDecl + "\n")
		}
		var imp []string
		add := func(p, n string) {
			if n != path.Base(p) {
				imp = append(imp, n+" "+strconv.Quote(p))
			} else {
				imp = append(imp, strconv.Quote(p))
			}
		}
		if o.mark {
			add("zoo/mark", "mark")
		}
		if o.fill {
			add("reflect", "reflect")
		}
		for p, n := range o.imports {
			add(p, n)
		}
		sort.Slice(imp, func(i, j int) bool { return importPath(imp[i]) < importPath(imp[j]) })
		var src strings.Builder
		src.WriteString(GeneratedHeader + "\n")
		fmt.Fprintf(&src, "// Input: %s %s; generator: model-author skeleton %d.\n\n", pp, g.in.Version, skelGenVersion)
		fmt.Fprintf(&src, "// Package %s is a skeleton of %s %s for the zoo (docs/DESIGN-package-models.md, 6.8): the exported API of the package, with\n", o.pkg.Name(), pp, g.in.Version)
		src.WriteString("// bodies that only record the dangerous arguments of the sink rows with zoo/mark (and return zero values). It is not the package:\n")
		src.WriteString("// the real code is never fetched into the zoo or run.\n")
		fmt.Fprintf(&src, "package %s\n\n", o.pkg.Name())
		if len(imp) > 0 {
			src.WriteString("import (\n")
			for _, i := range imp {
				src.WriteString("\t" + i + "\n")
			}
			src.WriteString(")\n\n")
		}
		src.WriteString(body.String())
		out, err := format.Source([]byte(src.String()))
		if err != nil {
			// the text is kept as it is: the build of the skeleton reports the error with the line
			out = []byte(src.String())
		}
		files = append(files, skelFile{Dir: dir, Name: o.pkg.Name() + ".go", Content: string(out)})
	}
	return files
}

func importPath(s string) string {
	i := strings.Index(s, `"`)
	return strings.Trim(s[i:], `"`)
}

// fillHelper sets the string fields of the struct that obj points to to the text: what a binder of a request does.
const fillHelper = `// zooFill sets the string fields of the struct that obj points to to the text of the request.
func zooFill(obj any, v string) {
	rv := reflect.ValueOf(obj)
	if rv.Kind() != reflect.Pointer || rv.Elem().Kind() != reflect.Struct {
		return
	}
	e := rv.Elem()
	for i := 0; i < e.NumField(); i++ {
		if f := e.Field(i); f.Kind() == reflect.String && f.CanSet() {
			f.SetString(v)
		}
	}
}
`

// zooVDecl is the marker of the case: a value that a function of the package returns for what a user of the service wrote. A
// constructor that is not generated (zoo_extra.go: the zoo's own way to make a client) sets it with mark.Src.
const zooVDecl = `// zooV is the marker of the case that the values of the skeleton carry where the package returns what a user of the service wrote.
// A hand written file of the skeleton sets it (mark.Src).
var zooV string
`
